    # results subfolder
    body_results_subfolder = os.path.join(experiment_full_path, 'body_results')

    nframes_each = []
    for v_idx, c_vid in enumerate(sorted_names):
        vcap = cv2.VideoCapture(c_vid)
        if vcap.isOpened():
            wo = int(vcap.get(3))  # float `width`
            ho = int(vcap.get(4))
            fps_in = int(vcap.get(5))  # float `height`
            nframes_each.append(int(vcap.get(7)))
        vcap.release()

    nframes = np.sum(nframes_each).astype(dtype=int)
    scale = np.array(body_vid_width / wo, dtype=float)
    body_vid_height = np.ceil(ho * (body_vid_width / wo)).astype(int)
    if body_vid_height % 2 > 0:
        body_vid_height = body_vid_height + 1

