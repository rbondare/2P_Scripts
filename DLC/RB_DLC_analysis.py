def fit_ellipse(pts):
    # fit ellipse to array of points
    # pts is array of xy coordinates: [x1,y1,x2,y2,x3,y3,...]
    # return center of ellips, major, minor axis, tilt, area

    # init values to 0
    center = [0, 0]
    width_2, height_2, theta, area = 0, 0, 0, 0
    success_yn = 0
    npts = np.int(len(pts) / 2)

    try:
        reg = LsqEllipse().fit(pts.reshape((npts, 2)))
        center, width_2, height_2, theta = reg.as_parameters()
        area = width_2 * height_2 * np.pi
        success_yn = 1
    except:  # error fitting ellipse, usually if some points are not in general position (eg. all points are 0)
        pass
    return center, width_2, height_2, theta, area, success_yn


def clean_point_array(pts_all, ll_thresh, median_filter_window):
    # array pts_all has (x,y,likelihood) values per each point
    # pts_all is (n, p*3) array, where n is the number of frames, p is the number of points per frame

    # remove the points with low likelihood and interpolate
    # pass median filter to remove jitter

    # (3 values per each point)
    npts = np.int(pts_all.shape[1] / 3)
    xy_ind = [[i * 3, i * 3 + 1] for i in range(npts)]
    xy_ind = [item for sublist in xy_ind for item in sublist]
    # get only x,y coordinates
    clean_xy_pts = pts_all[:, xy_ind]

    # get the likelihood values
    llind = [i * 3 + 2 for i in range(npts)]
    ll = pts_all[:, llind]
    # filter values with low likelihood

    # filter eye_values, point by point
    ll_low = np.where(ll < ll_thresh)
    num_low_vals = len(ll_low[0])

    # set to 'nan' (x,y) values where likelihood is low
    for ilow in range(len(ll_low[0])):
        fi = ll_low[0][ilow]  # frame index
        pi = ll_low[1][ilow]  # point index
        clean_xy_pts[fi, pi * 2] = float('nan')  # set x to nan
        clean_xy_pts[fi, pi * 2 + 1] = float('nan')  # set y to nan

    # linearly interpolate nan values and median filter to remove jitter
    for i in range(npts):
        xc = clean_xy_pts[:, i * 2]
        yc = clean_xy_pts[:, i * 2 + 1]
        nans, t = nan_helper(xc)
        try:
            if len(t(nans)) != 0:
                xc[nans] = np.interp(t(nans), t(~nans), xc[~nans])
                yc[nans] = np.interp(t(nans), t(~nans), yc[~nans])
        except:
            print('All values are below threshold.')

        # median filter
        xc = scipy.ndimage.median_filter(xc, median_filter_window)
        yc = scipy.ndimage.median_filter(yc, median_filter_window)
        clean_xy_pts[:, i * 2] = xc
        clean_xy_pts[:, i * 2 + 1] = yc

    return clean_xy_pts, num_low_vals


