def get_jackknife_indices(ntotal, nholdoppout, nrep=10):
    # randomly selects nrep subsets of (ntotal-nholdout) out of ntotal
    # if nholdout is 1 and ntotal <= 10 the script returns all possible subsets
    nholdout = nholdoppout
    nhold = ntotal - nholdout
    if nholdout == 1 and ntotal <= 10:
        inds = np.zeros((ntotal, nhold), dtype=int)
        for i in range(ntotal):
            inds[i] = np.concatenate([np.arange(i), np.arange(i + 1, ntotal)])
    else:
        inds = np.zeros((nrep, nhold), dtype=int)
        all_inds = np.arange(ntotal)
        for i in range(nrep):
            inds_i = np.random.permutation(all_inds)
            inds[i] = inds_i[:nhold]
    return inds


def find_az_el(eye, eye_r, pupil_2d):
    # find z of the iris as the intersection of the line thru iris 2d perpendicular to the image plane with the eyeball
    # there are two intersection points
    # assumption is that the image (and iris_2d point) are located at z=0 value and the center of eye at z=-eye_r value
    # then the point we need is the point in the interval [-eye_r,0]
    # z1=eye[3]-np.sqrt(eye_r**2-(iris_2d[1]-eye[1])**2-(iris_2d[2]-eye[2])**2)
    # eye is the 3D coordinates of the eye center
    # eye_r is the radius of the eye
    # iris_2d are the 2D coordinates of the pupil
    # return values: elevation, azimuth, and 3d location of the pupil

    z = eye[2] + np.sqrt(eye_r ** 2 - (pupil_2d[0] - eye[0]) ** 2 - (pupil_2d[1] - eye[1]) ** 2)
    iris_3d = np.array([pupil_2d[0], pupil_2d[1], z])

    # coordinates of the iris relative to the center of the eye
    x = iris_3d[0] - eye[0];
    y = -(iris_3d[1] - eye[1]);  # opencv's center of the coordinate frame is in the top left corner
    z = iris_3d[2] - eye[2];
    xz = np.sqrt(x ** 2 + z ** 2)  # length of the projection of the iris center on XZ plane
    el = 90 - np.arccos(y / eye_r) * 180 / np.pi
    az = 90 - np.arccos(x / xz) * 180 / np.pi
    return el, az, iris_3d


def get_eye_dlc_label_names_npts(cur_csv_file):
    # parses the header of a dlc file with eye labels
    # returns the names of the labels and how many eye, pupil, and reflection points were annotated

    with open(cur_csv_file, mode='r') as res_file:
        csv_reader = csv.reader(res_file, delimiter=',')
        line_count = 0
        for row in csv_reader:
            if line_count == 1:
                labels_dlc = row
                pupil_inds = [i for i, s in enumerate(row) if 'pupil' in s]
                eye_inds = [i for i, s in enumerate(row) if 'eye' in s]
                corneal_inds = [i for i, s in enumerate(row) if 'corneal' in s]
                if pupil_inds == []:
                    print(
                        'No pupil indices were found in the DLC file. The 2nd row of the DLC file should contain labels with the label *pupil*')
                if eye_inds == []:
                    print(
                        'No eye indices were found in the DLC file. The 2nd row of the DLC file should contain labels with the label *eye*')
                if corneal_inds == []:
                    print(
                        'No corneal reflection indices were found in the DLC file. The 2nd row of the DLC file should contain labels with the label *corneal*')
                break
            line_count += 1
    return labels_dlc, eye_inds, pupil_inds, corneal_inds


