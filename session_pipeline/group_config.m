function pairs = group_config()
% GROUP_CONFIG  The cohort: one entry per matched baseline/drug recording pair.
%
% Single source of truth for which recordings enter the group analysis --
% group_notebook.m and any batch driver both call this, so a figure and a
% table can never be built from different cohorts.
%
%   baseline_file  = column 1 of the ROI-match mapping (baseline session)
%   drug_file      = column 2 (drug session)
%   roi_match_file = roiMatch_plane<P>_<date>_<t1>_<t2>_V1.mat; the plane is
%                    inferred from this name (plane0 -> plane idx 1), and each
%                    session must be organized AT THAT PLANE (run_organize.m).
%   plane_base /   = 1-based planes, set explicitly when the two sessions were
%   plane_drug       matched ACROSS planes because the FOV drifted in z. The
%                    filename can only carry one number, so it is not enough.
%                    0310: 1246 plane2 <-> 1341 plane0, matched on purpose
%                    (verified: matched centroids 4.5 px apart vs 282 px
%                    shuffled, corr 1.000 -- and it is the only one of the 9
%                    plane combinations that matches at all).
%   condition      = drug label; pairs are pooled within condition.

    root = fileparts(fileparts(mfilename('fullpath')));      % 2P_Scripts/
    agg  = "Z:\joeschgrp\Group Members\Rima\Aggregated\";
    rm   = string(fullfile(root, 'roi_matching')) + filesep;

    pairs = struct( ...
        'baseline_file', { ...
            agg + "AnimalRB19_260305_1327_preprocessed.mat", ...
            agg + "AnimalRB19_260320_1444_preprocessed.mat", ...
            agg + "AnimalRB19_260312_1115_preprocessed.mat", ...
            agg + "AnimalRB19_260310_1246_preprocessed.mat"}, ...
        'drug_file', { ...
            agg + "AnimalRB19_260305_1409_preprocessed.mat", ...
            agg + "AnimalRB19_260320_1609_preprocessed.mat", ...
            agg + "AnimalRB19_260312_1243_preprocessed.mat", ...
            agg + "AnimalRB19_260310_1341_preprocessed.mat"}, ...
        'roi_match_file', { ...
            rm + "roiMatch_plane0_0305_1327_1409_V1.mat", ...
            rm + "roiMatch_plane2_0320_1444_1609_V1.mat", ...
            rm + "roiMatch_plane1_0312_1115_1243_V1.mat", ...
            rm + "roiMatch_plane1_0310_1246_1341_V1.mat"}, ...
        'plane_base', {[], [], [], 3}, ...      % 0310 baseline = plane2 (z-drift)
        'plane_drug', {[], [], [], 1}, ...      % 0310 drug     = plane0
        'condition', {'guanfacine', 'guanfacine', 'yohimbine', 'yohimbine'});
end
